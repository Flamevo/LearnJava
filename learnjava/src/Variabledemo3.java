public class Variabledemo3 {
    public static void main(String[] args){
        //定义Byte
        byte b = 10;
        System.out.println(b);
        
        //定义short
        short s = 100;
        System.out.println(s);

        //定义long 后面必须加上L作为后缀
        long l = 10000000000L;
        System.out.println(l);

        //定义float 后面必须加上f作为后缀 
        float f = 3.14F;
        System.out.println(f);
        //定义double
        double d = 3.14;
        System.out.println(d);
    }
}
