public class ArrDemo3 {
    public static void main(String[] args){
        int [] arr = {1, 2, 3, 4, 5};
        for(int i = 0; i < 5; i++){ //数组遍历
            System.out.println(arr[i]);
        }

        //数组length属性获取数组长度 arr.length
        for (int i = 0; i < arr.length; i++) {
            System.out.println(arr[i]);
        }
    }
}
